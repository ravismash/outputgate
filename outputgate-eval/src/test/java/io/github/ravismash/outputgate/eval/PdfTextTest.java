package io.github.ravismash.outputgate.eval;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import io.github.ravismash.outputgate.Contract;
import io.github.ravismash.outputgate.EvalContext;
import io.github.ravismash.outputgate.ProvenanceGate;
import io.github.ravismash.outputgate.SourceDocument;
import io.github.ravismash.outputgate.Verdict;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.font.PDType1Font;
import org.apache.pdfbox.pdmodel.font.Standard14Fonts;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/** PDFs are generated by the test itself, so nothing real is checked in. */
class PdfTextTest {

    @TempDir
    Path dir;

    private Path pdf(List<List<String>> pages) throws IOException {
        Path file = dir.resolve("test-" + pages.hashCode() + ".pdf");
        try (PDDocument doc = new PDDocument()) {
            for (List<String> lines : pages) {
                PDPage page = new PDPage();
                doc.addPage(page);
                try (PDPageContentStream s = new PDPageContentStream(doc, page)) {
                    s.beginText();
                    s.setFont(new PDType1Font(Standard14Fonts.FontName.HELVETICA), 12);
                    s.newLineAtOffset(72, 720);
                    for (String line : lines) {
                        s.showText(line);
                        s.newLineAtOffset(0, -16);
                    }
                    s.endText();
                }
            }
            doc.save(file.toFile());
        }
        return file;
    }

    @Test
    @DisplayName("each PDF page becomes one page of text, in order")
    void pagesInOrder() throws IOException {
        SourceDocument doc = PdfText.load(pdf(List.of(
                List.of("Invoice # 581482-1", "Invoice Date 10/21/12"),
                List.of("Gross Advertising Fee $22,466.00", "Net Advertising Fee $15,563.32"))));
        assertEquals(2, doc.pages().size());
        assertTrue(doc.pages().get(0).contains("Invoice # 581482-1"), doc.pages().get(0));
        assertTrue(doc.pages().get(1).contains("Net Advertising Fee $15,563.32"), doc.pages().get(1));
        assertTrue(!doc.pages().get(0).contains("Gross"), "page 2 text must not leak into page 1");
    }

    @Test
    @DisplayName("the extracted text grounds a quoted span with ProvenanceGate")
    void groundsSpans() throws IOException {
        SourceDocument doc = PdfText.load(pdf(List.of(List.of("Net Advertising Fee $15,563.32"))));
        Contract c = Contract.builder().gate(ProvenanceGate.builder().require("net").grounded().build()).build();
        String real = "{\"net\": {\"value\": 15563.32, \"source_span\": {\"page\": 1, \"text\": \"Net Advertising Fee $15,563.32\"}}}";
        String fake = "{\"net\": {\"value\": 15563.32, \"source_span\": {\"page\": 1, \"text\": \"Net due $15,563.32\"}}}";
        Verdict ok = c.evaluate(real, EvalContext.empty().withSource(doc));
        assertTrue(ok.passed(), ok::toString);
        assertTrue(!c.evaluate(fake, EvalContext.empty().withSource(doc)).passed());
    }

    @Test
    @DisplayName("a PDF with no text layer (e.g. a scan) is an error, not an empty document")
    void noTextLayer() throws IOException {
        Path blank = pdf(List.of(List.of()));
        IllegalArgumentException e = assertThrows(IllegalArgumentException.class, () -> PdfText.load(blank));
        assertTrue(e.getMessage().contains("no text"), e.getMessage());
    }

    @Test
    @DisplayName("a missing file or a file that is not a PDF is an error naming the file")
    void badFiles() throws IOException {
        Path missing = dir.resolve("missing.pdf");
        assertTrue(assertThrows(IllegalArgumentException.class, () -> PdfText.load(missing)).getMessage().contains("missing.pdf"));
        Path notPdf = Files.writeString(dir.resolve("notes.pdf"), "hello");
        assertTrue(assertThrows(IllegalArgumentException.class, () -> PdfText.load(notPdf)).getMessage().contains("notes.pdf"));
    }
}
